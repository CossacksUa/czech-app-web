let editRuleIdx = -1; let modalRuleData = { ua: { title: '', content: '', category: '' }, ru: { title: '', content: '', category: '' } }; let modalActiveLang = 'ua';
function openRuleModal(idx = -1) {
    if (!currentUser) return alert(t('msg_auth_req'));
    if (idx >= 0 && rules[idx].locked && !isAdmin()) return alert(t('msg_locked'));
    editRuleIdx = idx; modalActiveLang = currentLang;
    if (idx >= 0) {
        let r = rules[idx];
        modalRuleData = {
            ua: { title: r.title_ua || '', content: r.content_ua || '', category: r.category_ua || '' },
            ru: { title: r.title_ru || '', content: r.content_ru || '', category: r.category_ru || '' }
        };
    } else {
        modalRuleData = { ua: { title: '', content: '', category: '' }, ru: { title: '', content: '', category: '' } };
    }
    applyModalData(); document.getElementById('ruleModal').classList.add('active');
}

function closeRuleModal() { document.getElementById('ruleModal').classList.remove('active'); }

